// Checks on the deploy script, the status claims and the submission kit (T2964).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { root } from './helpers.js';

const read = (...p) => readFileSync(join(root, ...p), 'utf8');
const script = read('scripts', 'deploy-preview.ps1');
const STATUS_RE = /<!-- deploy-status:start -->([\s\S]*?)<!-- deploy-status:end -->/;
const DOCS = ['README.md', join('submission', 'devpost.md')];

test('the deploy script refuses without a login, uses the current wrangler commands, and checks the address', () => {
  assert.match(script, /wrangler whoami/);
  assert.match(script, /npx wrangler login/);
  assert.match(script, /wrangler pages project create \$Project --production-branch main/);
  assert.match(script, /wrangler pages deploy public --project-name \$Project --branch main/);
  assert.match(script, /https:\/\/scriptsold\.pages\.dev/);
  assert.match(script, /curl\.exe/);
  assert.match(script, /'200'/);
  assert.match(script, /<script type="module" src="app\.js"><\/script>/);
  // the whoami check comes before any project or deploy command
  assert.ok(script.indexOf('wrangler whoami') < script.indexOf('pages project create'));
  assert.ok(script.indexOf('Stop-WithStep }') < script.indexOf('pages project create'));
});

test('the deploy script never logs in, never uses a temporary account, never touches DNS or the custom domain', () => {
  for (const line of script.split('\n')) {
    const code = line.trim();
    if (code.startsWith('#') || /Write-Host/.test(code) || /-match/.test(code)) continue;
    assert.ok(!/wrangler login/.test(code), `runs a login: ${code}`);
    assert.ok(!/--temporary|auth login|token create|dns|pages domain|zone/i.test(code), `forbidden step: ${code}`);
    assert.ok(!/scriptsold\.com/.test(code), `touches the custom domain: ${code}`);
  }
});

test('the status block is flipped only by the script: docs say not deployed, or LIVE with a check time', () => {
  for (const f of DOCS) {
    const m = read(f).match(STATUS_RE);
    assert.ok(m, `${f} has no status block`);
    const body = m[1].trim();
    const notYet = /^Status: not deployed yet\./.test(body);
    const live = /^Status: LIVE\. https:\/\/\S+ returned HTTP 200 with the engine script tag at \d{4}-\d{2}-\d{2} \d{2}:\d{2} UTC/.test(body);
    assert.ok(notYet || live, `${f}: status block is neither state: ${body}`);
  }
  assert.match(script, /deploy-status:start/);
  assert.match(script, /Status: LIVE\./);
});

test('no doc claims the site is live outside its status block', () => {
  const files = [...DOCS, join('submission', 'kiro-usage.md'), join('submission', 'demo-script.md')];
  for (const f of files) {
    const text = read(f).replace(STATUS_RE, '');
    assert.ok(!/\b(is live|now live|goes live|live at|live now|deployed to|deployed at)\b/i.test(text), `${f} claims the site is live`);
  }
  assert.ok(read('README.md').includes('https://scriptsold.pages.dev (after the deploy step)'));
  assert.ok(read('submission', 'devpost.md').includes('https://scriptsold.pages.dev (after the deploy step)'));
  // the public page never states a live address either
  assert.ok(!/pages\.dev/.test(read('public', 'index.html')));
});

test('the submission kit exists and does not claim Kiro wrote the code', () => {
  for (const f of ['devpost.md', 'demo-script.md', 'kiro-usage.md']) assert.ok(existsSync(join(root, 'submission', f)), f);
  const all = ['devpost.md', 'demo-script.md', 'kiro-usage.md'].map((f) => read('submission', f)).join('\n');
  assert.ok(!/\bbuilt (entirely )?(with|by) Kiro\b/i.test(all.replace(/Do not submit the sentence "built with Kiro"/, '').replace(/an app built with Kiro/g, '')), 'claims it was built with Kiro');
  assert.match(read('submission', 'kiro-usage.md'), /not generated by Kiro|were not generated by Kiro/);
  assert.match(read('submission', 'kiro-usage.md'), /NEEDS SAUL/);
});

test('the demo script is under three minutes and its word counts are right', () => {
  const text = read('submission', 'demo-script.md');
  let total = 0;
  let seconds = 0;
  for (const line of text.split('\n')) {
    const m = line.match(/^\| (\d+):(\d+) to (\d+):(\d+) \|.*\| "(.*)" \| (\d+) \|$/);
    if (!m) continue;
    const words = m[5].split(/\s+/).length;
    assert.equal(words, Number(m[6]), `word count wrong for: ${m[5].slice(0, 40)}`);
    total += words;
    seconds = Number(m[3]) * 60 + Number(m[4]);
  }
  assert.ok(total > 100);
  assert.ok(seconds < 180, `ends at ${seconds}s`);
  assert.match(text, new RegExp(`Total: ${total} words`));
});
